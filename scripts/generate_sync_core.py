"""Generate the pure sync policy used by Qt and Android."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs(root):
    spec = json.loads((root / 'protocol/sync_rules.json').read_text())
    cpp = ['// Generated by scripts/generate_sync_core.py; edit protocol/sync_rules.json.', '#pragma once',
           '#include <QHash>', '#include <QString>', 'namespace Thoughts::SyncCore {',
           'struct Decision { QString action; QString reason; };', f'inline constexpr int rulesVersion = {spec["version"]};']
    kt = ['// Generated by scripts/generate_sync_core.py; edit protocol/sync_rules.json.',
          'package org.tbend.thoughts.sdk', '', 'object SyncCore {',
          '    data class Decision(val action: String, val reason: String)', f'    const val RULES_VERSION = {spec["version"]}']
    for key, name in [('source_rules', 'sourceDecision'), ('sync_rules', 'nextAction')]:
        cpp += [f'inline Decision {name}(const QHash<QString, bool> &facts) {{']
        kt += [f'    fun {name}(facts: Map<String, Boolean>): Decision {{']
        required = sorted({fact for rule in spec[key] for fact in rule['when']})
        cpp += ['    if (' + ' || '.join(f'!facts.contains(QStringLiteral("{key}"))' for key in required) + ') return {QStringLiteral("needs_attention"), QStringLiteral("missing_policy_facts")};']
        kt += ['        if (' + ' || '.join(f'!facts.containsKey("{key}")' for key in required) + ') return Decision("needs_attention", "missing_policy_facts")']
        for rule in spec[key]:
            cond = rule['when']; act = rule['action']; why = rule['reason']
            cc = ' && '.join(('' if v else '!') + f'facts.value(QStringLiteral("{k}"), false)' for k, v in cond.items()) or 'true'
            kc = ' && '.join(f'(facts["{k}"] == true)' if v else f'(facts["{k}"] != true)' for k, v in cond.items()) or 'true'
            cpp += [f'    if ({cc}) return {{QStringLiteral("{act}"), QStringLiteral("{why}")}};']
            kt += [f'        if ({kc}) return Decision("{act}", "{why}")']
        cpp += ['    return {QStringLiteral("needs_attention"), QStringLiteral("incomplete_policy")};', '}']
        kt += ['        error("incomplete sync policy")', '    }']
    cpp += ['}']; kt += ['}']
    return {'sdk/cpp/include/thoughts/synccore.h': '\n'.join(cpp) + '\n',
            'sdk/kotlin/src/main/kotlin/org/tbend/thoughts/sdk/SyncCore.kt': '\n'.join(kt) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in outputs(ROOT).items():
        dest = ROOT / path
        if args.check:
            if not dest.exists() or dest.read_text() != text:
                stale.append(path)
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text)
    if stale:
        raise SystemExit('Regenerate shared sync policy: ' + ', '.join(stale))
