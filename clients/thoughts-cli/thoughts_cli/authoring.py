@dataclass
class Entry:
    replacement: str
    explanation: str
    comment: str
    start_line: int = 0
    end_line: int = 0
    id: str = ""
    before: str = ""
    start: int = 0
    end: int = 0
    offset: int = 0
    # Where the wrapper goes and what it holds: the range [start, end) with before and replacement,
    # except beside a review card marker (lay_out_beside_card_markers).
    wrap_start: int = 0
    wrap_end: int = 0
    wrap_original: str = ""
    wrap_replacement: str = ""


@dataclass
class AuthoringRequest:
    command: str
    source: str
    expected_source_sha256: str
    conversation_id: str
    request_id: str
    entries: list[Entry]
    conversation_url: str = ""
    proposal_id: str = ""
    raw: dict[str, Any] = field(default_factory=dict)

    @property
    def create(self) -> bool:
        return self.command in {CREATE, CREATE_BATCH}

    @property
    def batch(self) -> bool:
        return self.command == CREATE_BATCH

    @property
    def remove(self) -> bool:
        return self.command == REMOVE


def _valid_uuid(value: str) -> bool:
    return UUID_PATTERN.fullmatch(value) is not None and value != "00000000-0000-0000-0000-000000000000"


def _positive_integer(value: Any) -> bool:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    if isinstance(value, float) and (not math.isfinite(value) or not value.is_integer()):
        return False
    return 1 <= value <= MAX_LINE


def request_sha256(request: dict[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(request, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    ).hexdigest()


def validate_request(request: Any) -> AuthoringRequest:
    """The desktop's request checks, in its order, before any source is read."""
    if not isinstance(request, dict):
        raise AuthoringRefused("invalid_request", "The request must be a JSON object.")
    command = request.get("command")
    if command not in {CREATE, CREATE_BATCH, REVISE, REMOVE}:
        raise AuthoringRefused("invalid_request", "Unknown proposal operation.")
    batch = command == CREATE_BATCH
    create = command in {CREATE, CREATE_BATCH}
    remove = command == REMOVE
    allowed = ["command", "source", "expected_source_sha256", "conversation_id", "request_id"]
    if not batch:
        # A withdrawal takes no replacement: the proposal's captured original text comes back.
        allowed[2:2] = ["explanation"] if remove else ["replacement", "explanation"]
    text_fields = list(allowed)
    if batch:
        allowed.append("proposals")
    elif create:
        allowed += ["start_line", "end_line"]
    else:
        allowed.append("proposal_id")
        text_fields.append("proposal_id")
    # Optional on create (spec 3.6): the link to the conversation.
    conversation_url = request.get("conversation_url", "")
    if "conversation_url" in request and (
            not create or not isinstance(conversation_url, str) or not valid_conversation_url(conversation_url)):
        raise AuthoringRefused(
            "invalid_request", "conversation_url must be a Claude Code session or Codex thread link, on create only.")
    for key in request:
        if key not in allowed and key != "conversation_url":
            raise AuthoringRefused("invalid_request", f"Unexpected request field: {key}")
    for key in text_fields:
        if not isinstance(request.get(key), str):
            raise AuthoringRefused("invalid_request", f"Missing or invalid text field: {key}")
    request_id, conversation = request["request_id"], request["conversation_id"]
    expected = request["expected_source_sha256"]
    if not _valid_uuid(request_id) or not _valid_uuid(conversation) or not SHA256_PATTERN.fullmatch(expected):
        raise AuthoringRefused("invalid_request", "Provide UUID request/conversation IDs and a SHA-256 source version.")
    raw_entries: list[dict[str, Any]]
    if batch:
        proposals = request.get("proposals")
        if not isinstance(proposals, list) or not 1 <= len(proposals) <= MAX_PROPOSALS:
            raise AuthoringRefused("invalid_request", "proposals must be an array of 1 to 500 objects.")
        raw_entries = []
        for value in proposals:
            if (not isinstance(value, dict) or len(value) != 4 or not isinstance(value.get("replacement"), str)
                    or not isinstance(value.get("explanation"), str)
                    or "start_line" not in value or "end_line" not in value):
                raise AuthoringRefused(
                    "invalid_request", "Each proposal takes exactly start_line, end_line, replacement and explanation.")
            raw_entries.append(value)
    else:
        raw_entries = [request]
    fmt = source_format(request["source"])
    entries = []
    for value in raw_entries:
        replacement, explanation = value.get("replacement", ""), value["explanation"]
        if (qt_trimmed(explanation) == "" or "\0" in replacement or "\0" in explanation
                or utf16_length(replacement) > MAX_REPLACEMENT or utf16_length(explanation) > MAX_EXPLANATION):
            raise AuthoringRefused(
                "invalid_request",
                "Provide a nonempty explanation; text must be within size limits and contain no NUL.")
        if reason := text_refusal(fmt, replacement):
            refusal = _writer_error(reason)
            if reason == "unbalanced_braces":
                refusal.message += (
                    " A replacement must balance on its own. To repair an unclosed or extra brace of the file, select "
                    "the lines from where the group opens through where it should close and give the whole corrected "
                    "text: Thoughts accepts that selection although its original does not balance.")
            raise refusal
        if create and (not _positive_integer(value.get("start_line")) or not _positive_integer(value.get("end_line"))):
            raise AuthoringRefused("invalid_request", "Line boundaries must be positive integers.")
        # Markdown block markers occupy their own lines; that newline is part of
        # the replacement, so the source alone defines its complete contents.
        if fmt == "markdown" and replacement and not replacement.endswith("\n"):
            replacement += "\n"
        trimmed = qt_trimmed(explanation)
        entries.append(Entry(
            replacement=replacement,
            explanation=explanation,
            comment=trimmed if fmt == "markdown" else escape_latex_explanation(trimmed),
            start_line=int(value["start_line"]) if create else 0,
            end_line=int(value["end_line"]) if create else 0,
        ))
    return AuthoringRequest(
        command=command, source=request["source"], expected_source_sha256=expected, conversation_id=conversation,
        request_id=request_id, entries=entries, conversation_url=conversation_url if create else "",
        proposal_id=request.get("proposal_id", "") if not create else "", raw=request,
    )


def _writer_error(reason: str) -> AuthoringRefused:
    message = ("Nested proposals are not allowed; provide only the proposed replacement text."
               if reason == "nested_proposal" else issue_message(reason))
    return AuthoringRefused("invalid_proposal", message, reason=reason)


def _proposal_error(parsed: ParseResult, proposal_id: str) -> AuthoringRefused:
    code = next((issue.code for issue in parsed.issues if issue.id == proposal_id), UNKNOWN_ID)
    message = ("The pending proposal was not found in this source." if code == UNKNOWN_ID
               else issue_message(code))
    return AuthoringRefused(code, message, proposal_id=proposal_id)


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def _wrapper_ids(path: str, text: str) -> set[str]:
    """IDs read from every wrapper, valid or broken (AgentProposalParse::ids)."""
    parsed = parse(path, text)
    return {proposal.id for proposal in parsed.proposals} | {
        issue.id for issue in parsed.issues if issue.id is not None}


# Lines of new prose should hold one sentence each (Existing note protections).
# The desktop does not enforce this; the server only warns, conservatively.
_SENTENCE_BREAK = re.compile(r"[.!?][\"')\]]*\s+(?=[A-Z])")
_ABBREVIATIONS = frozenset({"e.g", "i.e", "cf", "vs", "etc", "al", "fig", "eq", "sec", "ch", "no", "dr", "mr", "ms",
                            "prof", "resp", "approx", "ref", "refs", "eqs", "figs"})


def _sentence_break(prose: str) -> bool:
    for match in _SENTENCE_BREAK.finditer(prose):
        word = re.search(r"(\S*)$", prose[:match.start()]).group(1).lstrip("([{\"'").lower()
        if len(word) <= 1 or word in _ABBREVIATIONS or "." in word:
            continue
        return True
    return False


def sentence_warnings(fmt: str | None, original: str, replacement: str) -> list[dict[str, Any]]:
    """Newly written replacement lines that seem to hold more than one sentence (non-blocking)."""
    existing = set(original.split("\n"))
    warnings = []
    for number, line in enumerate(replacement.split("\n"), 1):
        if line in existing or not line.strip():
            continue
        prose = line
        if fmt == "tex":
            match = re.search(r"(?<!\\)(?:\\\\)*%", prose)
            prose = prose[:match.start()] if match else prose
            prose = re.sub(r"\$[^$]*\$", "x", prose)
        if _sentence_break(prose):
            warnings.append({
                "code": "several_sentences_on_line", "line": number,
                "message": f"Line {number} of the proposed text seems to hold more than one sentence; "
                           "write each sentence on its own line.",
            })
    return warnings


@dataclass
class Authored:
    updated: str
    result: dict[str, Any]
    # Decision claims (protocol/agent-proposals.md 10.4.2) for the upload that carries ``updated``:
    # {proposal_id, action, wrapper_sha256, source_file}; the client adds decision_id, decided_at, origin.
    claims: list[dict[str, str]] = field(default_factory=list)


def withdraw(request: AuthoringRequest, path: str, source: str, parsed: ParseResult, previous_sha256: str) -> Authored:
    """Withdraw one pending proposal: its wrapper becomes its captured original text (the desktop's
    remove-proposal, which decides it as Reject would), and a withdraw claim names the exact wrapper.

    Half of a card move (protocol/agent-proposals.md 12) is withdrawn with its other half when that is
    pending in this source too; client.py withdraws a partner in another source (withdraw_partner)."""
    if not valid_proposal_id(request.proposal_id):
        raise AuthoringRefused("invalid_request", "Invalid proposal ID.")
    by_id = parsed.by_id()
    found = by_id.get(request.proposal_id)
    if found is None:
        raise _proposal_error(parsed, request.proposal_id)
    partner = move_partner(found.id)
    withdrawn = [found] + ([by_id[partner]] if partner in by_id else [])
    try:
        updated = decide(path, source, [proposal.id for proposal in withdrawn], "disregard")
    except ProposalRefused as refusal:
        raise _proposal_error(parsed, request.proposal_id) from refusal
    remaining = parse(path, updated)
    restored, cursor = [], 0
    for proposal in sorted(withdrawn, key=lambda proposal: proposal.start):
        restored += [source[cursor:proposal.start], proposal.original]
        cursor = proposal.end
    if (len(remaining.proposals) != len(parsed.proposals) - len(withdrawn) or len(remaining.issues) != len(parsed.issues)
            or any(proposal.id in remaining.by_id() for proposal in withdrawn)
            or updated != "".join(restored) + source[cursor:]):
        raise AuthoringRefused("invalid_proposal", "The original text could not be restored safely.")
    result: dict[str, Any] = {
        "schema_version": 1, "accepted": True, "terminal": True, "state": "proposal_removed", "source": path,
        "proposal_id": found.id, "created_at": found.created_at,
        "source_sha256": hashlib.sha256(updated.encode("utf-8")).hexdigest(), "previous_source_sha256": previous_sha256,
        "original_text": found.original, "withdrawn_replacement": found.replacement,
        "explanation": request.entries[0].explanation, "request_id": request.request_id,
        "conversation_id": found.conversation_id, "agent_conversation_id": request.conversation_id.lower(),
        "line": _line_of(source, found.start), "replayed": False,
        "message": "Proposal withdrawn and its original text restored on the server; "
                   "other devices receive it with their next Sync.",
    }
    if len(withdrawn) > 1:
        result["withdrawn_proposal_ids"] = [found.id, partner]
        result["message"] = MOVE_WITHDRAWN
    claims = [{"proposal_id": proposal.id, "action": "withdraw", "source_file": path,
               "wrapper_sha256": hashlib.sha256(source[proposal.start:proposal.end].encode("utf-8")).hexdigest()}
              for proposal in withdrawn]
    return Authored(updated, result, claims)


MOVE_WITHDRAWN = ("Move withdrawn: both halves removed and their original text restored on the server; "
                  "other devices receive it with their next Sync.")


def withdraw_partner(path: str, source: str, partner_id: str) -> tuple[str, dict[str, str]]:
    """The other half of a withdrawn card move, pending in another source: (that source with the half's
    original text restored, its withdraw claim)."""
    parsed = parse(path, source)
    found = parsed.by_id().get(partner_id)
    if found is None:
        raise _proposal_error(parsed, partner_id)
    updated = source[:found.start] + found.original + source[found.end:]
    remaining = parse(path, updated)
    if (len(remaining.proposals) != len(parsed.proposals) - 1 or len(remaining.issues) != len(parsed.issues)
            or partner_id in remaining.by_id()):
        raise AuthoringRefused("invalid_proposal", "The original text of the move's other half could not be restored safely.")
    return updated, {"proposal_id": partner_id, "action": "withdraw", "source_file": path,
                     "wrapper_sha256": hashlib.sha256(source[found.start:found.end].encode("utf-8")).hexdigest()}


def author(
    request: AuthoringRequest,
    path: str,
    source: str,
    *,
    now: datetime,
    new_id: Callable[[], str] = lambda: "agent-" + str(uuid.uuid4()),
    ids_elsewhere: Callable[[Iterable[str]], str | None] = lambda ids: None,
    previous_sha256: str = "",
) -> Authored:
    """Create or revise proposals in one source text (authorProposal after its checks of the file).

    ``ids_elsewhere(ids)`` names another source that already uses one of the IDs.
    """
    fmt = source_format(path)
    markdown = fmt == "markdown"
    parsed = parse(path, source)
    if request.remove:
        return withdraw(request, path, source, parsed, previous_sha256)
    entries = request.entries
    if request.create:
        for entry in entries:
            entry.id = new_id()
    elif not valid_proposal_id(request.proposal_id):
        raise AuthoringRefused("invalid_request", "Invalid proposal ID.")
    else:
        entries[0].id = request.proposal_id
    if (other := ids_elsewhere([entry.id for entry in entries])) is not None:
        raise AuthoringRefused("duplicate_id", f"This proposal ID also occurs in {other}.")
    conversation = request.conversation_id.lower()
    updated = source
    repair_warnings: list[dict[str, Any]] = []
    if request.create:
        boundaries = [0] + [index + 1 for index, character in enumerate(source) if character == "\n"]
        if boundaries[-1] != len(source):
            boundaries.append(len(source))
        # Broken wrappers occupy their span as well: wrapping one would nest it.
        occupied = [(proposal.start, proposal.end) for proposal in parsed.proposals]
        occupied += [(issue.start, issue.end) for issue in parsed.issues]
        for entry in entries:
            first, last = entry.start_line - 1, entry.end_line - 1
            if first > last or first >= len(boundaries) or last >= len(boundaries):
                raise AuthoringRefused(
                    "invalid_range", "Use one-based line boundaries with end_line exclusive; equal boundaries insert text.")
            entry.start, entry.end = boundaries[first], boundaries[last]
            for low, high in occupied:
                if (entry.start < high and entry.end > low) or (
                        entry.start == entry.end and low < entry.start < high):
                    raise AuthoringRefused(
                        "proposal_overlap", "The selected range intersects a pending proposal; revise that proposal instead.")
            entry.before = source[entry.start:entry.end]
            if entry.before == entry.replacement:
                raise AuthoringRefused("no_change", "The replacement is identical to the selected text.")
        # Ranges of one request may touch but not overlap, and two insertions
        # at the same boundary would have no defined order.
        order = sorted(range(len(entries)), key=lambda index: (entries[index].start, entries[index].end))
        for previous_index, next_index in zip(order, order[1:], strict=False):
            previous, following = entries[previous_index], entries[next_index]
            if previous.end > following.start or (
                    previous.start == previous.end and following.start == following.end
                    and previous.start == following.start):
                raise AuthoringRefused(
                    "proposal_overlap", "The proposals of one request must not overlap or insert at the same line.")
        # An unbalanced original is accepted when the proposals make the file balance (brace_repairs).
        if not markdown:
            for repaired, warning in brace_repairs(source, entries):
                index = next(i for i, entry in enumerate(entries) if entry is repaired)
                repair_warnings.append({**warning, **({"proposal_index": index} if request.batch else {})})
        created = format_timestamp(now)
        # A review card marker line stays alone while the proposals are pending.
        lay_out_beside_card_markers(source, entries, order, request.batch, latex=not markdown)
        # Original and replacement contents must round-trip byte-for-byte.
        pieces, cursor, shift = [], 0, 0
        for index in order:
            entry = entries[index]
            fields = ProposalFields(
                id=entry.id, created_at=created, conversation_id=conversation,
                conversation_url=request.conversation_url, explanation=qt_trimmed(entry.explanation),
                original=entry.wrap_original, replacement=entry.wrap_replacement)
            block, refusal = format_markdown(fields) if markdown else format_latex(fields)
            if not block:
                raise _writer_error(refusal)
            pieces += [source[cursor:entry.wrap_start], block]
            cursor = entry.wrap_end
            entry.offset = entry.wrap_start + shift
            shift += len(block) - (entry.wrap_end - entry.wrap_start)
        pieces.append(source[cursor:])
        updated = "".join(pieces)
    else:
        found = parsed.by_id().get(request.proposal_id)
        if found is None:
            raise _proposal_error(parsed, request.proposal_id)
        # A half of a move carries the card's passage verbatim; changing one half alone would break the pair (12).
        if move_partner(found.id) is not None:
            raise AuthoringRefused(
                "move_proposal", "This proposal is half of a card move and cannot be revised; withdraw it with "
                "remove_proposal (which withdraws both halves) and move the card again.")
        entry = entries[0]
        # Revisions never rewrite creation metadata, including the original conversation.
        created = found.created_at
        entry.before = found.original
        entry.offset = found.start
        entry.wrap_original, entry.wrap_replacement = found.original, entry.replacement
        entry.start, entry.end = found.start, found.end
        if markdown:
            fields = ProposalFields(
                id=found.id, created_at=found.created_at, conversation_id=found.conversation_id,
                conversation_url=found.conversation_url, explanation=entry.comment,
                original=found.original, replacement=entry.replacement)
            block, refusal = format_markdown(fields)
            if not block:
                raise _writer_error(refusal)
            updated = source[:found.start] + block + source[found.end:]
        else:
            # Revise in place, keeping the wrapper's own layout and metadata.
            assert found.explanation_start is not None and found.explanation_end is not None
            entry.wrap_replacement = revised_replacement(source, found, entry.replacement)
            updated = (source[:found.explanation_start] + entry.comment + "\n"
                       + source[found.explanation_end:found.replacement_start] + entry.wrap_replacement
                       + source[found.replacement_end:])
    result_parse = parse(path, updated)
    written: list[Proposal] = []
    by_id = result_parse.by_id()
    for entry in entries:
        found = by_id.get(entry.id)
        expected_explanation = entry.comment if markdown else entry.comment + "\n"
        if (found is None or found.start != entry.offset or found.original != entry.wrap_original
                or found.replacement != entry.wrap_replacement or found.created_at != created
                or found.explanation != expected_explanation):
            raise AuthoringRefused(
                "invalid_proposal",
                "The Markdown proposal did not round-trip exactly." if markdown else
                "The proposed text does not round-trip as a valid TeX argument; check balanced braces "
                "and include newlines after trailing comments.")
        written.append(found)
    if (len(result_parse.proposals) != len(parsed.proposals) + (len(entries) if request.create else 0)
            or len(result_parse.issues) != len(parsed.issues)):
        raise AuthoringRefused(
            "invalid_proposal",
            "The proposals changed other pending proposals; check balanced braces and include newlines "
            "after trailing comments.")
    if not markdown:
        # Every card marker outside the replaced text is still alone on its line (the layout's safety net).
        check_card_marker_lines(source, updated, [(entry.start, entry.end) for entry in entries],
                                [(found.start, found.end) for found in written])
    after_sha256 = hashlib.sha256(updated.encode("utf-8")).hexdigest()
    state = "proposals_created" if request.batch else "proposal_created" if request.create else "proposal_revised"
    result: dict[str, Any] = {
        "schema_version": 1, "accepted": True, "terminal": True, "state": state, "source": path,
        "source_sha256": after_sha256, "previous_source_sha256": previous_sha256,
        "request_id": request.request_id, "agent_conversation_id": conversation, "replayed": False,
    }
    proposals = []
    warnings = list(repair_warnings)
    for index, (entry, found) in enumerate(zip(entries, written, strict=True)):
        proposals.append({
            "proposal_id": entry.id, "created_at": created, "original_text": entry.before,
            "replacement": entry.replacement, "explanation": entry.explanation,
            "line": _line_of(updated, found.start),
        })
        for warning in sentence_warnings(fmt, entry.before, entry.replacement):
            if request.batch:
                warning["proposal_index"] = index
            warnings.append(warning)
    if written[0].conversation_url:
        result["conversation_url"] = written[0].conversation_url
    if request.batch:
        result["conversation_id"] = conversation
        result["proposals"] = proposals
        result["message"] = (f"Saved {len(entries)} pending proposals on the server; not accepted. "
                             "Other devices receive them with their next Sync.")
    else:
        result.update(proposals[0])
        result["conversation_id"] = written[0].conversation_id
        result["message"] = ("Saved on the server as a pending proposal; not accepted. "
                             "Other devices receive it with their next Sync.")
    if warnings:
        result["warnings"] = warnings
    return Authored(updated, result)


# ------------------------------------------------------------------ source owners (thoughts_server.source_owner)

CONNECTED_FOLDER = re.compile(r"docs-[A-Za-z0-9_.-]+")
DEFAULT_FOLDER = re.compile(r"\.thoughts/projects/[0-9a-f]{64}/(?:default|documents)")


def owner_relative(path: str) -> str:
    """The path inside its source folder (docs-x/... or a Project's default folder), else the path."""
    parts = path.split("/")
    if CONNECTED_FOLDER.fullmatch(parts[0]) and len(parts) > 1:
        return "/".join(parts[1:])
    if len(parts) > 4 and DEFAULT_FOLDER.fullmatch("/".join(parts[:4])):
        return "/".join(parts[4:])
    return path
