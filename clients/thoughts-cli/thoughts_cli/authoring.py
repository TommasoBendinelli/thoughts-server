class AuthoringRefused(Exception):
    """A refusal with the desktop's error_code; nothing was written."""

    def __init__(self, code: str, message: str, **extra: Any):
        super().__init__(message)
        self.code = code
        self.message = message
        self.extra = extra

    @property
    def status_code(self) -> int:
        if self.code in {"write_failed", "read_failed"}:
            return 503
        return 409 if self.code in CONFLICT_CODES else 422

    def body(self) -> dict[str, Any]:
        """The desktop's command error shape (thoughtscommandprotocol syncCommandError)."""
        return {
            "schema_version": 1, "accepted": False, "reused": False, "scope": "all",
            "state": "busy" if self.code == "busy" else "failed", "terminal": self.code != "busy",
            "message": self.message, "error_code": self.code, **self.extra,
        }


def issue_message(code: str) -> str:
    return ISSUE_MESSAGES.get(code, f"The proposal is invalid ({code}).")


# ------------------------------------------------------------------ text helpers

def _qt_space(character: str) -> bool:
    """QChar::isSpace: ASCII TAB..CR and space, NEL, and Unicode separators."""
    return character in "\t\n\v\f\r \x85" or unicodedata.category(character) in {"Zs", "Zl", "Zp"}


def qt_trimmed(text: str) -> str:
    """QString::trimmed, which the desktop applies to explanations."""
    start, end = 0, len(text)
    while start < end and _qt_space(text[start]):
        start += 1
    while end > start and _qt_space(text[end - 1]):
        end -= 1
    return text[start:end]


def utf16_length(text: str) -> int:
    """QString::size: the desktop's size limits count UTF-16 code units."""
    return len(text) + sum(1 for character in text if ord(character) > 0xFFFF)


def format_timestamp(value: datetime) -> str:
    """Spec 3.2: YYYY-MM-DDTHH:MM:SS.mmmZ in UTC."""
    utc = value.astimezone(UTC)
    return utc.strftime("%Y-%m-%dT%H:%M:%S.") + f"{utc.microsecond // 1000:03d}Z"


def escape_latex_explanation(text: str) -> str:
    """Spec 8.1: the explanation's escape table."""
    pieces = []
    for character in text:
        if character in "{}%$&#_":
            pieces.append("\\" + character)
        elif character == "\\":
            pieces.append("\\textbackslash{}")
        elif character == "^":
            pieces.append("\\textasciicircum{}")
        elif character == "~":
            pieces.append("\\textasciitilde{}")
        else:
            pieces.append(character)
    return "".join(pieces)


def text_refusal(fmt: str | None, text: str) -> str:
    """Whether text can be an original or replacement (spec 8): "" or the writer's refusal code."""
    if fmt == "markdown":
        return "nested_proposal" if _next_marker(text, 0) is not None else ""
    if fmt != "tex":
        return ""
    depth, index, n = 0, 0, len(text)
    while index < n:
        character = text[index]
        if character == "\\":
            # A final backslash would escape the closing brace of the argument.
            index += 1
            if index >= n:
                return "unbalanced_braces"
        elif character == "%":
            newline = text.find("\n", index)
            if newline < 0:
                return "unterminated_comment"
            index = newline
        elif character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth < 0:
                return "unbalanced_braces"
        index += 1
    if depth != 0:
        return "unbalanced_braces"
    return "nested_proposal" if next_live_wrapper(text, 0, n) is not None else ""


@dataclass(frozen=True)
class BraceDepth:
    """The §4.1 brace depth of a text: where it ends, its lowest point and where it first goes wrong."""
    final: int
    lowest: int
    # The first } that closes nothing (lowest < 0), else the first { never closed (final > 0), else -1.
    culprit: int


def _brace_steps(text: str):
    """(offset, +1 or -1) for every { and } that counts under spec 4.1 (escapes and comments skipped)."""
    index, n = 0, len(text)
    while index < n:
        character = text[index]
        if character == "\\":
            index += 2
            continue
        if character == "%":
            newline = text.find("\n", index)
            if newline < 0:
                return
            index = newline
        elif character == "{":
            yield index, 1
        elif character == "}":
            yield index, -1
        index += 1


def brace_depth(text: str) -> BraceDepth:
    depth = lowest = 0
    opened: list[int] = []
    first_extra = -1
    for offset, step in _brace_steps(text):
        depth += step
        if step > 0:
            opened.append(offset)
        elif opened:
            opened.pop()
        elif first_extra < 0:
            first_extra = offset
        lowest = min(lowest, depth)
    culprit = first_extra if first_extra >= 0 else (opened[0] if opened else -1)
    return BraceDepth(depth, lowest, culprit)


def balanced_original(original: str) -> tuple[str, str, str]:
    """original with the fewest braces added so that it balances: (text, added before, added after).

    Closing braces go at the end of its last line, or on a line of their own when that
    line ends in a comment; opening ones at its start."""
    depth = brace_depth(original)
    before, after = "{" * -depth.lowest, "}" * (depth.final - depth.lowest)
    body = before + original
    if not after:
        return body, before, after
    if body.endswith("\n"):
        last = body[:-1].rpartition("\n")[2]
        if re.search(r"(?<!\\)(?:\\\\)*%", last) is None:
            return body[:-1] + after + "\n", before, after
        return body + after + "\n", before, after + "\n"
    return body + after, before, after


def enclosing_balanced_lines(source: str, start: int, end: int, reach: int = 200) -> tuple[int, int] | None:
    """The smallest whole-line range around [start, end) whose braces balance, as one-based (start, end) lines."""
    boundaries = [0] + [index + 1 for index, character in enumerate(source) if character == "\n"]
    if boundaries[-1] != len(source):
        boundaries.append(len(source))
    lines = len(boundaries) - 1
    # depth at each line start, and the lowest depth reached inside each line
    at_start, lowest_in = [0] * (lines + 1), [0] * lines
    steps = list(_brace_steps(source))
    depth, cursor = 0, 0
    for line in range(lines):
        at_start[line] = depth
        low = depth
        while cursor < len(steps) and steps[cursor][0] < boundaries[line + 1]:
            depth += steps[cursor][1]
            low = min(low, depth)
            cursor += 1
        lowest_in[line] = low
    at_start[lines] = depth
    first = max(index for index in range(lines + 1) if boundaries[index] <= start)
    last = max(first + 1, min(index for index in range(lines + 1) if boundaries[index] >= end))
    best = None
    for low in range(first, max(-1, first - reach - 1), -1):
        floor = min(lowest_in[low:last]) if last > low else at_start[low]
        for high in range(last, min(lines, last + reach) + 1):
            if high > last:
                floor = min(floor, lowest_in[high - 1])
            if floor < at_start[low]:
                break
            if at_start[high] == at_start[low] and (best is None or high - low < best[1] - best[0]):
                best = (low, high)
                break
    return (best[0] + 1, best[1] + 1) if best else None


def brace_repairs(source: str, entries: list[Entry]) -> list[tuple[Entry, dict[str, Any]]]:
    """Let a proposal repair the file's braces (2026-11-10): an unbalanced original is accepted
    when the file does not balance and the file with every replacement does.

    A wrapper's original must balance (spec 8.1), so it is captured with the fewest braces
    added (balanced_original), and the explanation says so: Accept gives the replacement,
    Reject the original with those braces, which balances the file too. Otherwise the
    usual refusal, naming the line that opens or closes too much, or a range that balances."""
    unbalanced = [entry for entry in entries if text_refusal("tex", entry.before) == "unbalanced_braces"]
    if not unbalanced:
        return []
    whole = brace_depth(source)
    pieces, cursor = [], 0
    for entry in sorted(entries, key=lambda item: (item.start, item.end)):
        pieces += [source[cursor:entry.start], entry.replacement]
        cursor = entry.end
    pieces.append(source[cursor:])
    accepted = brace_depth("".join(pieces))
    file_broken = whole.final != 0 or whole.lowest < 0
    if not file_broken or accepted.final != 0 or accepted.lowest < 0:
        entry = unbalanced[0]
        first, last = _line_of(source, entry.start), _line_of(source, max(entry.start, entry.end - 1))
        if not file_broken:
            span = enclosing_balanced_lines(source, entry.start, entry.end)
            hint = f" Select whole groups instead, e.g. start_line {span[0]}, end_line {span[1]}." if span else ""
            raise AuthoringRefused(
                "invalid_proposal", f"The selected lines {first}-{last} do not balance their braces: they cut through "
                f"a {{ }} group.{hint} Nothing was written.", reason="unbalanced_braces",
                **({"suggested_start_line": span[0], "suggested_end_line": span[1]} if span else {}))
        culprit = _line_of(source, whole.culprit) if whole.culprit >= 0 else first
        what = "closes a brace that was never opened" if whole.lowest < 0 else "opens a brace that is never closed"
        raise AuthoringRefused(
            "invalid_proposal", f"The file does not balance its braces (line {culprit} {what}), and with the proposed "
            f"text it still does not. To repair it, select the lines from line {culprit} through where the group "
            "should close and give the complete corrected text, so that the file balances once it is accepted. "
            "Nothing was written.", reason="unbalanced_braces", unbalanced_line=culprit)
    warnings = []
    for entry in unbalanced:
        captured, before, after = balanced_original(entry.before)
        first, last = _line_of(source, entry.start), _line_of(source, max(entry.start, entry.end - 1))
        added = " and ".join(part for part in (
            f"{len(before)} opening brace(s) at its start" if before else "",
            f"{after.count('}')} closing brace(s) at its end" if after else "") if part)
        note = (f"Thoughts: lines {first}-{last} did not balance their braces, so the original kept with this "
                f"proposal has {added}; accepting gives the replacement, rejecting gives that original, and both "
                "balance the file.")
        entry.before = captured
        entry.explanation = qt_trimmed(entry.explanation) + "\n" + note
        entry.comment = escape_latex_explanation(qt_trimmed(entry.explanation))
        warnings.append((entry, {"code": "original_braces_balanced", "line": first, "added_before": before,
                                 "added_after": after, "message": note}))
    return warnings


@dataclass
class ProposalFields:
    id: str
    created_at: str
    conversation_id: str
    explanation: str
    original: str
    replacement: str
    conversation_url: str = ""


def _common_refusal(fields: ProposalFields) -> str:
    if not valid_proposal_id(fields.id):
        return "invalid_id"
    if (not valid_timestamp(fields.created_at) or not valid_conversation_id(fields.conversation_id)
            or fields.explanation.strip(" \t\n\r\f\v") == ""
            or (fields.conversation_url and not valid_conversation_url(fields.conversation_url))):
        return "invalid_metadata"
    return ""


def format_latex(fields: ProposalFields) -> tuple[str, str]:
    """(wrapper, "") or ("", refusal): formatLatexAgentProposal."""
    code = (_common_refusal(fields) or text_refusal("tex", fields.original)
            or text_refusal("tex", fields.replacement))
    if code:
        return "", code
    metadata = f"created={fields.created_at},conversation_id={fields.conversation_id}"
    if fields.conversation_url:
        metadata += f",conversation_url={fields.conversation_url}"
    return (f"\\agentProposedEdit[{metadata}]{{{fields.id}}}"
            f"{{{escape_latex_explanation(qt_trimmed(fields.explanation))}\n}}"
            f"{{{fields.original}}}{{{fields.replacement}}}"), ""


def _markdown_block(value: str) -> str:
    if not value:
        return ""
    return "".join(
        "| " + line.replace("&", "&amp;").replace("-->", "--&gt;") + "\n" for line in value.split("\n")
    )


def format_markdown(fields: ProposalFields) -> tuple[str, str]:
    """(block, "") or ("", refusal): formatMarkdownAgentProposal (spec 5.2, 8.2)."""
    code = (_common_refusal(fields) or text_refusal("markdown", fields.original)
            or text_refusal("markdown", fields.replacement))
    if code:
        return "", code
    start = (
        "<!-- thoughts:agent-proposal:v2:start\n"
        f"id: {fields.id}\n"
        f"created_at: {fields.created_at}\n"
        f"conversation_id: {fields.conversation_id}\n"
        + (f"conversation_url: {fields.conversation_url}\n" if fields.conversation_url else "")
        + "explanation:\n" + _markdown_block(qt_trimmed(fields.explanation))
        + "original_text:\n" + _markdown_block(fields.original)
        + "-->\n"
    )
    end = f"<!-- thoughts:agent-proposal:v2:end {fields.id} -->\n"
    newline = "\n" if fields.replacement and not fields.replacement.endswith("\n") else ""
    return start + fields.replacement + newline + end, ""


def is_generated_source(relative_path: str, text: str) -> bool:
    """Spec 8: generated sources take no new or revised proposals."""
    if "/tex/generated/" in "/" + relative_path.replace("\\", "/"):
        return True
    for line in text.split("\n"):
        if line.strip(" \t\n\r\f\v") == "":
            continue
        return line.startswith(GENERATED_PREFIXES)
    return False


