# Plan

@dataclass
class PlannedFile:
    source: str          # origin folder-relative path
    destination: str     # destination folder-relative path
    action: str          # move | copy | present
    reason: str
    sha256: str
    generated: bool = False
    used_by: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {"source": self.source, "destination": self.destination, "action": self.action,
                "reason": self.reason, "sha256": self.sha256, "generated": self.generated,
                "used_by": self.used_by}


def free_name(paths: frozenset[str] | set[str], wanted: str) -> str:
    if wanted not in paths:
        return wanted
    stem, suffix = posixpath.splitext(wanted)
    number = 2
    while f"{stem}_{number}{suffix}" in paths:
        number += 1
    return f"{stem}_{number}{suffix}"


def _package_commands(name: str, package_source: Callable[[str], str | None] | None) -> set[str]:
    commands = set(KNOWN_PACKAGE_COMMANDS.get(name, set()))
    if package_source is not None:
        text = package_source(name)
        if text:
            # Only new public names: packages also patch kernel commands (\\label).
            commands.update(name for name, definition in definitions(text).items()
                            if definition.definer in PUBLIC_DEFINERS and "@" not in name)
    return commands


def analyse(origin: Folder, destination: Folder, document: str, destination_document: str, *,
            other_documents: list[str], destination_documents: list[str],
            package_source: Callable[[str], str | None] | None = None,
            document_format: str = "latex") -> dict:
    """Plan moving ``document`` (origin-relative) to ``destination_document`` (destination-relative).

    ``other_documents`` are the origin folder's other declared documents, and
    ``destination_documents`` the destination folder's declared documents.
    """
    text = origin.text(document)
    if text is None:
        raise ValueError("The document's source is unavailable on the server. Sync and try again")
    origin_preamble = preamble_files(origin) if document_format == "latex" else set()
    destination_preamble = preamble_files(destination) if document_format == "latex" else set()
    origin_bibs = project_bibliographies(origin, origin_preamble)
    references, closure = dependency_closure(origin, document, skip=origin_preamble)
    dependency_files = sorted(f for f in closure if f not in origin_preamble and f not in origin_bibs)

    users: dict[str, list[str]] = {}
    for other in other_documents:
        if other == document or other not in origin.paths:
            continue
        _, other_closure = dependency_closure(origin, other, skip=origin_preamble)
        for path in other_closure:
            users.setdefault(path, []).append(other)

    files: list[PlannedFile] = []
    unresolved = []
    for reference in references:
        if reference.resolved is None and reference.kind in {"tex", "graphic", "listing", "bibliography"}:
            unresolved.append({"file": reference.file, "command": reference.command, "argument": reference.argument})
    taken = set(destination.paths)
    renamed: dict[str, str] = {}
    for path in dependency_files:
        raw = origin.bytes(path)
        digest = origin.sha256(path) or ""
        generated = is_generated(path, raw)
        shared = sorted(users.get(path, []))
        target = path
        existing = destination.sha256(target)
        if existing is not None and existing == digest:
            files.append(PlannedFile(path, target, "present", "already in the destination, identical", digest,
                                     generated, shared))
            # A moved, unshared file that the destination already has is retired at its origin.
            if not shared and not generated:
                files[-1].reason = "already in the destination, identical; removed from the origin"
                files[-1].action = "present-move"
            continue
        if existing is not None or target in taken:
            stem = PurePosixPath(destination_document).stem
            parent = posixpath.dirname(path)
            target = free_name(taken, posixpath.join(parent, stem + "-" + posixpath.basename(path)) if parent else stem + "-" + path)
            renamed[path] = target
        taken.add(target)
        if generated:
            action, reason = "copy", "generated input: copied as a fixed file; its generator stays in the origin"
        elif shared:
            action, reason = "copy", "also used by " + ", ".join(PurePosixPath(s).name for s in shared)
        else:
            action, reason = "move", "used only by this document"
        if path in renamed:
            reason += "; renamed because the destination has a different file at " + path
        files.append(PlannedFile(path, target, action, reason, digest, generated, shared))

    # Every wrapped build loads the folder's manual_style, so a destination folder
    # without one could not build the document at all: it receives the origin's
    # project preamble files (an existing identical file is reused, a different
    # one is kept and the definitions are compared against it).
    style_copies: dict[str, str] = {}
    if document_format == "latex" and not standalone(text) and origin_preamble and not destination_preamble:
        for path in sorted(origin_preamble):
            digest = origin.sha256(path) or ""
            existing = destination.sha256(path)
            if existing is not None:
                if existing == digest:
                    files.append(PlannedFile(path, path, "present", "already in the destination, identical", digest))
                    style_copies[path] = origin.text(path) or ""
                elif path.endswith(".sty") and PurePosixPath(path).stem == PREAMBLE_ENTRY:
                    style_copies[path] = destination.text(path) or ""
                continue
            files.append(PlannedFile(path, path, "copy",
                                     "the destination folder has no project style; copied so this document "
                                     "builds and looks as before", digest))
            taken.add(path)
            style_copies[path] = origin.text(path) or ""
        destination_preamble = set(style_copies)

    def destination_text(path: str) -> str:
        return style_copies[path] if path in style_copies else destination.text(path) or ""

    # Rewrite references to renamed dependencies inside the moved/copied files.
    edits_by_file: dict[str, list[Edit]] = {}
    if renamed:
        for reference in references:
            if reference.command == "image":
                continue  # Markdown links and images are rewritten below, from the new place.
            if reference.resolved in renamed:
                old_target = reference.resolved
                new_target = renamed[old_target]
                argument = _clean_reference(reference.argument)
                if argument.endswith(posixpath.basename(old_target)) or old_target.endswith(argument) or (old_target.startswith(argument)):
                    replacement = _replace_tail(argument, old_target, new_target)
                    if reference.argument.strip().startswith('"'):
                        replacement = '"' + replacement + '"'
                    edits_by_file.setdefault(reference.file, []).append(
                        Edit(reference.span[0], reference.span[1], replacement, "renamed dependency"))

    # Preamble requirements of a document that relies on the project preamble.
    preamble = {"applies": False, "missing": [], "different": [], "packages": [], "carried": "",
                "origin_files": sorted(origin_preamble), "destination_files": sorted(destination_preamble)}
    moved_texts = [text] + [origin.text(f.source) or "" for f in files
                            if f.source.endswith((".tex", ".sty")) and f.action != "present"
                            and f.source not in style_copies]
    if document_format == "latex" and not standalone(text):
        preamble["applies"] = True
        used = set()
        own = {}
        for value in moved_texts:
            used |= uses(value)
            own.update(definitions(value))
        origin_definitions: dict[str, Definition] = {}
        for path in sorted(origin_preamble):
            origin_definitions.update({k: v for k, v in definitions(origin.text(path) or "", path).items()
                                       if k not in origin_definitions})
        destination_definitions: dict[str, Definition] = {}
        for path in sorted(destination_preamble):
            destination_definitions.update(definitions(destination_text(path), path))
        origin_packages = []
        for path in sorted(origin_preamble):
            origin_packages += [p for p in packages(origin.text(path) or "") if p not in origin_packages]
        destination_packages = []
        for path in sorted(destination_preamble):
            destination_packages += [p for p in packages(destination_text(path)) if p not in destination_packages]
        # A carried definition brings what its body uses: \\docTitle needs the
        # helper macros and conditionals it expands, \\DefineVerbatimEnvironment
        # needs fancyvrb/fvextra.
        required = {n for n in used if n in origin_definitions and n not in own}
        pending = [n for n in required if n not in destination_definitions]
        while pending:
            for name in uses(origin_definitions[pending.pop()].source):
                if name in origin_definitions and name not in own and name not in required:
                    required.add(name)
                    if name not in destination_definitions:
                        pending.append(name)
        for name in required:
            if name not in destination_definitions:
                used |= uses(origin_definitions[name].source)
        needed = sorted(required)
        missing = [n for n in needed if n not in destination_definitions]
        different = [n for n in needed if n in destination_definitions
                     and _squash(origin_definitions[n].source) != _squash(destination_definitions[n].source)]
        local_packages = {PurePosixPath(p).stem for p in origin_preamble if p.endswith(".sty")}
        package_rows = []
        for name in origin_packages:
            if name in destination_packages or name in local_packages:
                continue
            provided = _package_commands(name, package_source)
            needed_from = sorted(used & provided - set(own) - set(destination_definitions))
            package_rows.append({"name": name, "used": needed_from, "required": bool(needed_from)})
        preamble["missing"] = [{"name": n, "defined_in": origin_definitions[n].file,
                                "definition": origin_definitions[n].source} for n in missing]
        preamble["different"] = [{"name": n, "origin": origin_definitions[n].file,
                                  "destination": destination_definitions[n].file} for n in different]
        preamble["packages"] = package_rows
        file_order = {path: index for index, path in enumerate(sorted(origin_preamble))}
        preamble["carried"] = carried_preamble(
            [r["name"] for r in package_rows if r["required"]],
            sorted((origin_definitions[n] for n in missing), key=lambda d: (file_order.get(d.file, 0), d.start, d.name)),
            origin.owner)
        preamble["destination_files"] = sorted(destination_preamble)
        if style_copies:
            preamble["style_copied"] = sorted(p for p in style_copies
                                              if any(f.source == p and f.action == "copy" for f in files))
        elif not destination_preamble:
            preamble["destination_without_preamble"] = True

    # Bibliography entries the destination lacks.
    bibliography = {"applies": False, "missing": [], "unavailable": [], "target": None}
    cited = []
    for value in moved_texts:
        cited += [k for k in cited_keys(value) if k not in cited]
    if document_format == "latex" and cited and any(has_bibliography(t) for t in moved_texts):
        bibliography["applies"] = True
        destination_bibs = project_bibliographies(destination, destination_preamble)
        destination_keys = set()
        for path in destination_bibs:
            destination_keys |= set(bib_entries(destination.text(path) or ""))
        origin_entries = {}
        for path in origin_bibs:
            for key, value in bib_entries(origin.text(path) or "").items():
                origin_entries.setdefault(key, value)
        writable = [p for p in destination_bibs if not is_generated(p, destination.bytes(p))]
        bibliography["target"] = writable[0] if writable else None
        for key in cited:
            if key in destination_keys:
                continue
            if key in origin_entries:
                bibliography["missing"].append({"key": key, "entry": origin_entries[key]})
            else:
                bibliography["unavailable"].append(key)

    # Links inside moved files, and inbound links are computed by the caller (they span Projects).
    moved_paths = {f.source: f.destination for f in files if f.action in {"move", "present-move"}}
    placed = {f.source: f.destination for f in files}
    new_places = {document: destination_document, **placed}
    for path, value in [(document, text)] + [(f.source, origin.text(f.source) or "") for f in files
                                             if f.source.endswith((".tex", ".md", ".markdown"))
                                             and f.action in {"move", "copy"}]:
        if path.endswith((".md", ".markdown")):
            edits = markdown_link_edits_for_moved_file(value, origin.owner, destination.owner, path,
                                                       new_places[path], (document, destination_document), placed)
        else:
            edits = link_edits_for_moved_file(value, origin.owner, destination.owner, (document, destination_document),
                                              other_documents, moved_paths, destination_documents)
        if edits:
            edits_by_file.setdefault(path, []).extend(edits)

    markers = {
        "review_cards": len(re.findall(r"\\ReviewCardMaskStart\{", text)),
        "comments": len(set(re.findall(r"\\Comment(?:Anchor|Highlight)\{([^}]*)\}", text))),
        "proposals": len(re.findall(r"\\agentProposedEdit\b", text)),
    }
    return {
        "document": document,
        "destination_document": destination_document,
        "files": [f.as_dict() for f in files],
        "unresolved": unresolved,
        "preamble": preamble,
        "bibliography": bibliography,
        "edits": {path: [{"start": e.start, "end": e.end, "replacement": e.replacement, "reason": e.reason}
                         for e in sorted(edits, key=lambda e: e.start)]
                  for path, edits in edits_by_file.items()},
        "markers": markers,
    }


def _squash(value: str) -> str:
    return re.sub(r"\s+", "", value).replace("\\providecommand", "\\newcommand").replace("\\renewcommand", "\\newcommand")


def _replace_tail(argument: str, old_target: str, new_target: str) -> str:
    """Replace the part of ``old_target`` an argument names with the matching part of ``new_target``."""
    old_name, new_name = posixpath.basename(old_target), posixpath.basename(new_target)
    old_stem, new_stem = posixpath.splitext(old_name)[0], posixpath.splitext(new_name)[0]
    if argument.endswith(old_name):
        prefix = argument[:-len(old_name)]
        return prefix + new_name if not prefix or old_target.endswith(argument) else prefix + new_name
    if argument.endswith(old_stem):
        return argument[:-len(old_stem)] + new_stem
    return argument


def carried_preamble(package_names: list[str], missing: list[Definition], origin_owner: str) -> str:
    """A guarded, document-local preamble block; empty when nothing is missing."""
    if not package_names and not missing:
        return ""
    lines = [CARRIED_BEGIN,
             f"% Carried from {origin_owner}'s project preamble when this document moved.",
             "% Each definition applies only where this Project's own preamble lacks it.",
             "\\makeatletter"]
    for name in package_names:
        lines.append(f"\\RequirePackage{{{name}}}")
    for definition in missing:
        source = definition.source.strip()
        if definition.name.startswith("env:"):
            environment = definition.name[4:]
            lines.append(f"\\@ifundefined{{{environment}}}{{%\n{source}%\n}}{{}}")
        elif definition.name.startswith("col:"):
            lines.append(source)
        else:
            command = definition.name[1:]
            lines.append(f"\\@ifundefined{{{command}}}{{%\n{source}%\n}}{{}}")
    lines += ["\\makeatother", CARRIED_END, ""]
    return "\n".join(lines)


def insert_preamble(text: str, block: str) -> str:
    """Insert a carried block before ``\\begin{document}`` (or at the top)."""
    if not block:
        return text
    clean = strip_comments(text)
    match = re.search(r"\\begin\s*\{document\}", clean)
    position = match.start() if match else 0
    line_start = text.rfind("\n", 0, position) + 1
    if text[line_start:position].strip():
        return text[:position] + "\n" + block + text[position:]
    return text[:line_start] + block + text[line_start:]


def append_bibliography(text: str, entries: list[dict], origin_owner: str) -> str:
    if not entries:
        return text
    lines = [] if text.endswith("\n") or not text else [""]
    lines.append(f"% Entries carried from {origin_owner} with a moved document.")
    for entry in entries:
        lines.append(entry["entry"].rstrip())
        lines.append("")
    return text + "\n".join(lines)
