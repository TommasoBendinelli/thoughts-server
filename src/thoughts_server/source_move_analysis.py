@dataclass
class Edit:
    start: int
    end: int
    replacement: str
    reason: str


def apply_edits(text: str, edits: list[Edit]) -> str:
    for edit in sorted(edits, key=lambda e: e.start, reverse=True):
        text = text[:edit.start] + edit.replacement + text[edit.end:]
    return text


def _command_edit(text: str, call: Call, name: str, first_argument: str, reason: str) -> Edit:
    """Rewrite ``\\Old{selector}`` as ``\\New{new selector}`` keeping the remaining arguments verbatim."""
    start = call.start
    end = call.argument_spans[0][1] + 1
    return Edit(start, end, "\\" + name + "{" + first_argument + "}", reason)


def link_edits_for_moved_file(text: str, origin: str, destination: str, moved_doc: tuple[str, str],
                              origin_documents: list[str], moved_paths: dict[str, str],
                              destination_documents: list[str]) -> list[Edit]:
    """Links inside a moved file whose meaning changes once it lives in the destination."""
    clean = strip_comments(text)
    edits = []
    old_relative, new_relative = moved_doc
    for call in calls(clean, LINK_COMMANDS, arguments=1, max_optional=0):
        target = call.arguments[0].strip()
        if call.name == "SourceLink":
            path = target
            if path == old_relative:
                continue
            if path in moved_paths:
                if moved_paths[path] != path:
                    edits.append(_command_edit(text, call, "SourceLink", moved_paths[path], "moved target"))
                continue
            edits.append(_command_edit(text, call, "CrossSourceLink", origin + "/" + path,
                                       "link to a source that stays in the origin Project"))
        elif call.name == "CrossSourceLink":
            if target.startswith(destination + "/"):
                edits.append(_command_edit(text, call, "SourceLink", target[len(destination) + 1:],
                                           "link into its new Project"))
        elif call.name == "PdfLink":
            edits.append(_command_edit(text, call, "CrossPdfLink", origin + "/" + target,
                                       "PDF stays in the origin Project"))
        elif call.name == "CrossPdfLink":
            if target.startswith(destination + "/"):
                edits.append(_command_edit(text, call, "PdfLink", target[len(destination) + 1:],
                                           "PDF of its new Project"))
    return edits


def inbound_link_edits(text: str, file_owner: str, origin: str, destination: str,
                       moved_doc: tuple[str, str]) -> list[Edit]:
    """Links in another document that point at the moved document."""
    clean = strip_comments(text)
    old_relative, new_relative = moved_doc
    edits = []
    for call in calls(clean, LINK_COMMANDS, arguments=1, max_optional=0):
        target = call.arguments[0].strip()
        if call.name == "SourceLink" and file_owner == origin and target == old_relative:
            edits.append(_command_edit(text, call, "CrossSourceLink", destination + "/" + new_relative,
                                       "the linked source moved"))
        elif call.name == "CrossSourceLink" and target == origin + "/" + old_relative:
            if file_owner == destination:
                edits.append(_command_edit(text, call, "SourceLink", new_relative, "the linked source moved"))
            else:
                edits.append(_command_edit(text, call, "CrossSourceLink", destination + "/" + new_relative,
                                           "the linked source moved"))
    return edits


def _markdown_link_edit(text: str, span, folder: str, file_path: str, new_folder: str, new_path: str,
                        new_target: str, pdf_key: str | None) -> Edit | None:
    """Rewrite one link destination so it names new_target from new_folder/new_path.

    The written spelling is kept whenever it still resolves to the same
    target. A PDF link becomes the bare filename within the PDF's own folder
    (\\PdfLink) and a path to that folder's root elsewhere (\\CrossPdfLink).
    """
    from . import markdown_links
    parts = markdown_links.split_href(span.href)
    path, fragment = parts[0], parts[1]
    if pdf_key is not None:
        owner = new_target
        wanted = ("PdfLink", pdf_key) if owner == new_folder else ("CrossPdfLink", f"{owner}/{pdf_key}")
        current = markdown_links.classify(span.href, new_folder, new_path)
        if current is not None and (current.kind, current.target) == wanted:
            return None
        written = f"{pdf_key}.pdf" if owner == new_folder else (
            markdown_links.relative_href(owner, new_folder, new_path) + f"/{pdf_key}.pdf")
    else:
        if markdown_links.resolve_path(new_folder, new_path, path) == new_target:
            return None
        written = markdown_links.relative_href(new_target, new_folder, new_path)
    replacement = markdown_links.write_href(written, fragment, span.bracketed)
    if replacement == span.href:
        return None
    return Edit(span.start, span.end, replacement, "")


def _markdown_link_target(href: str, folder: str, file_path: str) -> tuple[str, str | None] | None:
    """(target, pdf key) a relative Markdown href names: a docs-root path, or for a
    PDF link the folder whose PDF it names. None for links nothing moves."""
    from . import markdown_links
    from .source_owner import owner_of
    parts = markdown_links.split_href(href)
    if parts is None or not parts[0] or parts[2]:
        return None
    path = parts[0]
    link = markdown_links.classify(href, folder, file_path)
    if link is not None and link.kind == "PdfLink":
        return folder, link.target
    if link is not None and link.kind == "CrossPdfLink":
        owner, key = link.target.split("/", 1)
        return owner, key
    resolved = markdown_links.resolve_path(folder, file_path, path)
    if resolved is None or owner_of(resolved) is None:
        return None
    return resolved, None


def markdown_link_edits_for_moved_file(text: str, origin: str, destination: str, old_path: str, new_path: str,
                                       moved_doc: tuple[str, str], placed: dict[str, str]) -> list[Edit]:
    """Relative links and images in a moved Markdown file, as seen from its new place.

    ``placed`` maps origin-relative files to where the destination holds them
    after the move (moved, copied or already present). Everything else stays
    in the origin, so a link to it now leaves the folder; a link to a file of
    the destination now stays inside it. The same decisions as the LaTeX
    table: \\SourceLink <-> \\CrossSourceLink and \\PdfLink <-> \\CrossPdfLink.
    """
    from . import markdown_links
    old_document, new_document = moved_doc
    edits = []
    for span in markdown_links.link_spans(text):
        found = _markdown_link_target(span.href, origin, old_path)
        if found is None:
            continue
        target, key = found
        if key is None:
            if target == f"{origin}/{old_document}":
                target = f"{destination}/{new_document}"
            elif target.startswith(origin + "/") and target[len(origin) + 1:] in placed:
                target = f"{destination}/{placed[target[len(origin) + 1:]]}"
        edit = _markdown_link_edit(text, span, origin, old_path, destination, new_path, target, key)
        if edit is not None:
            edit.reason = "relative link from the document's new folder"
            edits.append(edit)
    return edits


def markdown_inbound_link_edits(text: str, file_path: str, origin: str, destination: str,
                                moved_doc: tuple[str, str]) -> list[Edit]:
    """Links in a Markdown document (docs-root-relative ``file_path``) to the moved document."""
    from . import markdown_links
    from .source_owner import split
    located = split(file_path)
    if located is None:
        return []
    folder, path = located
    old_relative, new_relative = moved_doc
    edits = []
    for span in markdown_links.link_spans(text):
        if span.image:
            continue
        found = _markdown_link_target(span.href, folder, path)
        if found is None or found[1] is not None or found[0] != f"{origin}/{old_relative}":
            continue
        edit = _markdown_link_edit(text, span, folder, path, folder, path, f"{destination}/{new_relative}", None)
        if edit is not None:
            edit.reason = "the linked source moved"
            edits.append(edit)
    return edits


