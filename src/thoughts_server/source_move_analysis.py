"""Analyse what moving one source document into another source folder needs.

Everything here is pure: a ``Folder`` maps folder-relative paths to bytes, so
the same analysis runs on the server's canonical sources and on a plain
directory (tests and dry runs). The analysis decides

* which files the document depends on, and whether each one moves (only this
  document uses it), is copied (another document of the origin folder uses it,
  or it is a generated input whose generator stays behind), or is already
  present unchanged in the destination;
* which commands, environments, column types and packages the document takes
  from the origin folder's project preamble (``manual_style`` and the files it
  loads) that the destination's preamble lacks, and a document-local preamble
  block that carries them; a destination folder without any project preamble
  receives a copy of the origin's instead, since every wrapped build loads it;
* which bibliography entries the destination lacks;
* which semantic links (SourceLink/PdfLink and their Cross variants)
  must be rewritten in the moved files and in other documents so that no build
  fails on a link whose target changed Project.
"""
