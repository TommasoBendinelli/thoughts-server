class Folder:
    """Folder-relative files of one source folder, read lazily."""

    def __init__(self, owner: str, paths: Iterable[str], read: Callable[[str], bytes | None],
                 sha256: Callable[[str], str] | None = None):
        self.owner = owner
        self.paths = frozenset(paths)
        self._read = read
        self._sha = sha256
        self._cache: dict[str, bytes | None] = {}

    def bytes(self, path: str) -> bytes | None:
        if path not in self.paths:
            return None
        if path not in self._cache:
            self._cache[path] = self._read(path)
        return self._cache[path]

    def text(self, path: str) -> str | None:
        raw = self.bytes(path)
        if raw is None:
            return None
        return raw.decode("utf-8", errors="replace")

    def sha256(self, path: str) -> str | None:
        if path not in self.paths:
            return None
        if self._sha is not None:
            return self._sha(path)
        raw = self.bytes(path)
        return None if raw is None else hashlib.sha256(raw).hexdigest()


def strip_comments(text: str) -> str:
    """Blank TeX comments and verbatim bodies while keeping offsets and line numbers."""
    out = []
    for line in text.split("\n"):
        index = 0
        cut = len(line)
        while index < len(line):
            char = line[index]
            if char == "\\":
                index += 2
                continue
            if char == "%":
                cut = index
                break
            index += 1
        out.append(line[:cut] + " " * (len(line) - cut))
    result = "\n".join(out)
    for environment in VERBATIM_ENVIRONMENTS:
        pattern = re.compile(r"\\begin\{" + re.escape(environment) + r"\}(.*?)\\end\{" + re.escape(environment) + r"\}", re.S)
        result = pattern.sub(lambda m: m.group(0)[:len("\\begin{" + environment + "}")]
                             + re.sub(r"[^\n]", " ", m.group(1))
                             + "\\end{" + environment + "}", result)
    return result


def _skip_space(text: str, index: int) -> int:
    while index < len(text) and text[index] in " \t\r\n":
        index += 1
    return index


def balanced(text: str, index: int, open_char: str = "{", close_char: str = "}") -> tuple[str, int] | None:
    """Return the group content starting at ``text[index] == open_char`` and the index after it."""
    if index >= len(text) or text[index] != open_char:
        return None
    depth = 0
    position = index
    while position < len(text):
        char = text[position]
        if char == "\\":
            position += 2
            continue
        if char == open_char:
            depth += 1
        elif char == close_char:
            depth -= 1
            if depth == 0:
                return text[index + 1:position], position + 1
        position += 1
    return None


@dataclass
class Call:
    name: str
    start: int
    end: int
    optional: list[str]
    arguments: list[str]
    argument_spans: list[tuple[int, int]]


def calls(clean: str, names: Iterable[str], *, arguments: int = 1, max_optional: int = 2) -> list[Call]:
    """Find ``\\name*[opt]{arg}...`` calls in comment-free text."""
    wanted = "|".join(sorted((re.escape(n) for n in names), key=len, reverse=True))
    found = []
    for match in re.finditer(r"\\(" + wanted + r")(?![A-Za-z@])", clean):
        index = match.end()
        if index < len(clean) and clean[index] == "*":
            index += 1
        optional = []
        args, spans = [], []
        index = _skip_space(clean, index)
        while len(optional) < max_optional and index < len(clean) and clean[index] == "[":
            group = balanced(clean, index, "[", "]")
            if group is None:
                break
            optional.append(group[0])
            index = _skip_space(clean, group[1])
        for position in range(arguments):
            if position:
                index = _skip_space(clean, index)
            group = balanced(clean, index)
            if group is None:
                break
            args.append(group[0])
            spans.append((index + 1, group[1] - 1))
            index = group[1]
        if len(args) == arguments:
            found.append(Call(match.group(1), match.start(), index, optional, args, spans))
    return found


def _clean_reference(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        value = value[1:-1]
    return value.strip()


def _normalized(path: str) -> str | None:
    if not path or path.startswith("/") or "\\" in path or "#" in path or "\n" in path:
        return None
    normalized = posixpath.normpath(path)
    if normalized.startswith("../") or normalized == ".." or normalized == ".":
        return None
    return normalized


@dataclass
class Reference:
    """One file reference inside a scanned file."""
    file: str            # the folder-relative file that contains the reference
    command: str
    argument: str        # the raw argument text as written
    span: tuple[int, int]
    kind: str            # tex | graphic | listing | bibliography | package | class
    resolved: str | None = None


def resolve(folder: Folder, reference: str, suffixes: Iterable[str], base: str, roots: Iterable[str],
            extra_dirs: Iterable[str] = ()) -> str | None:
    """Mirror the compiler's search: base directory, then recursive TEXINPUTS-style roots."""
    reference = _clean_reference(reference)
    if not reference or reference.startswith("/"):
        return None
    candidates = []
    for suffix in suffixes:
        name = reference + suffix if suffix and not reference.endswith(suffix) else reference
        if name not in candidates:
            candidates.append(name)
    for directory in (base, *extra_dirs):
        for name in candidates:
            path = _normalized(posixpath.join(directory, name) if directory not in ("", ".") else name)
            if path and path in folder.paths:
                return path
    for root in roots:
        for name in candidates:
            normalized_name = _normalized(name)
            if normalized_name is None:
                continue
            prefix = "" if root in ("", ".") else root.rstrip("/") + "/"
            matches = sorted((p for p in folder.paths if p.startswith(prefix)
                              and (p == prefix + normalized_name or p.endswith("/" + normalized_name))),
                             key=lambda p: (p.count("/"), p))
            if matches:
                return matches[0]
    return None


SEARCH_ROOTS = ("tex/source", "", "tex/support")
BIB_ROOTS = ("tex/support", "tex/generated", "")


def file_references(folder: Folder, path: str, base: str = ".") -> list[Reference]:
    """Direct file references of one source file (not recursive)."""
    text = folder.text(path)
    if text is None:
        return []
    clean = strip_comments(text)
    references: list[Reference] = []
    graphic_dirs = []
    for call in calls(clean, ["graphicspath"]):
        graphic_dirs.extend(_clean_reference(d) for d in re.findall(r"\{([^{}]*)\}", call.arguments[0]))

    def add(call, argument, span, kind, suffixes, roots=SEARCH_ROOTS, directory=base, extra=()):
        resolved = resolve(folder, argument, suffixes, directory, roots, extra)
        references.append(Reference(path, call.name, argument, span, kind, resolved))

    for call in calls(clean, [n for n in INPUT_COMMANDS if INPUT_COMMANDS[n] is not None]):
        add(call, call.arguments[0], call.argument_spans[0], "tex", INPUT_COMMANDS[call.name])
    for call in calls(clean, GRAPHIC_COMMANDS):
        add(call, call.arguments[0], call.argument_spans[0], "graphic", GRAPHIC_COMMANDS[call.name],
            extra=[d.rstrip("/") for d in graphic_dirs])
    for call in calls(clean, LISTING_COMMANDS):
        add(call, call.arguments[0], call.argument_spans[0], "listing", ("",))
    for call in calls(clean, ["inputminted"], arguments=2):
        add(call, call.arguments[1], call.argument_spans[1], "listing", ("",))
    for call in calls(clean, IMPORT_COMMANDS, arguments=2):
        directory = _clean_reference(call.arguments[0]).rstrip("/")
        relative = IMPORT_COMMANDS[call.name]
        anchor = posixpath.dirname(path) if relative else "."
        joined = _normalized(posixpath.join(anchor, directory) if anchor not in ("", ".") else directory) or directory
        resolved = resolve(folder, call.arguments[1], TEX_SUFFIXES, joined, ())
        reference = Reference(path, call.name, call.arguments[1], call.argument_spans[1], "tex", resolved)
        reference.import_base = joined  # type: ignore[attr-defined]
        references.append(reference)
    for call in calls(clean, ["bibliography", "addbibresource", "addglobalbib"]):
        start = call.argument_spans[0][0]
        offset = 0
        for part in call.arguments[0].split(","):
            stripped = part.strip()
            if stripped:
                inner = start + offset + part.index(stripped)
                resolved = resolve(folder, stripped, (".bib", ""), base, BIB_ROOTS)
                references.append(Reference(path, call.name, stripped, (inner, inner + len(stripped)), "bibliography", resolved))
            offset += len(part) + 1
    for call in calls(clean, ["usepackage", "RequirePackage"]):
        for part in call.arguments[0].split(","):
            name = part.strip()
            if name:
                resolved = resolve(folder, name, (".sty",), base, SEARCH_ROOTS)
                references.append(Reference(path, call.name, name, call.argument_spans[0], "package", resolved))
    for call in calls(clean, ["documentclass", "LoadClass"]):
        name = call.arguments[0].strip()
        resolved = resolve(folder, name, (".cls",), base, SEARCH_ROOTS)
        references.append(Reference(path, call.name, name, call.argument_spans[0], "class", resolved))
    for call in calls(clean, ["IfFileExists"], arguments=1):
        name = _clean_reference(call.arguments[0])
        resolved = resolve(folder, name, ("",), base, SEARCH_ROOTS)
        if resolved and resolved.endswith((".sty", ".tex", ".bib")):
            kind = "package" if resolved.endswith(".sty") else "bibliography" if resolved.endswith(".bib") else "tex"
            references.append(Reference(path, call.name, call.arguments[0], call.argument_spans[0], kind, resolved))
    if path.endswith((".md", ".markdown")):
        for match in re.finditer(r"!\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)", text):
            target = match.group(1)
            if re.match(r"[a-z]+:", target):
                continue
            resolved = resolve(folder, target, ("",), posixpath.dirname(path) or ".", ())
            references.append(Reference(path, "image", target, match.span(1), "graphic", resolved))
    references.sort(key=lambda r: r.span)
    return references


def dependency_closure(folder: Folder, path: str, *, skip: Iterable[str] = ()) -> tuple[list[Reference], set[str]]:
    """All references reachable from ``path`` and the set of files they resolve to."""
    skip = set(skip)
    seen = {path}
    references: list[Reference] = []
    pending = [(path, ".")]
    while pending:
        current, base = pending.pop()
        for reference in file_references(folder, current, base):
            references.append(reference)
            target = reference.resolved
            if target is None or target in skip:
                continue
            if target not in seen:
                seen.add(target)
                if target.endswith((".tex", ".sty", ".cls", ".md", ".markdown")):
                    pending.append((target, getattr(reference, "import_base", base)))
    seen.discard(path)
    return references, seen


def preamble_files(folder: Folder) -> set[str]:
    """The project preamble: ``manual_style.sty`` and the folder files it loads."""
    entry = resolve(folder, PREAMBLE_ENTRY, (".sty",), ".", SEARCH_ROOTS)
    if entry is None:
        return set()
    _, files = dependency_closure(folder, entry)
    return {entry} | {f for f in files if not f.endswith(".bib")}


def project_bibliographies(folder: Folder, preamble: set[str]) -> list[str]:
    """Bibliography files the project preamble names, in preference order."""
    result = []
    for path in sorted(preamble):
        for reference in file_references(folder, path):
            if reference.kind == "bibliography" and reference.resolved and reference.resolved not in result:
                result.append(reference.resolved)
    # The conventional project bibliography, when the preamble names none explicitly.
    for conventional in ("tex/generated/references.bib", "tex/support/references.bib"):
        if not result and conventional in folder.paths:
            result.append(conventional)
    return result


@dataclass
class Definition:
    name: str
    source: str
    file: str
    definer: str = ""
    start: int = 0


def definitions(text: str, file: str = "") -> dict[str, Definition]:
    """Commands (``\\name``), environments (``env:name``) and column types (``col:X``) a file defines."""
    clean = strip_comments(text)
    result: dict[str, Definition] = {}

    def snippet(start: int, end: int) -> str:
        return text[start:end]

    for match in re.finditer(r"\\(" + "|".join(sorted(DEFINERS_COMMAND | DEFINERS_ENVIRONMENT | DEFINERS_DEF
                                                       | {"newcolumntype"}, key=len, reverse=True)) + r")(?![A-Za-z@])\*?",
                             clean):
        definer = match.group(1)
        index = _skip_space(clean, match.end())
        name = None
        if definer in DEFINERS_DEF:
            command = re.match(r"\\([A-Za-z@]+|.)", clean[index:])
            if not command:
                continue
            name = "\\" + command.group(1)
            end = index + command.end()
            if definer == "let":
                tail = re.match(r"\s*=?\s*\\([A-Za-z@]+|.)", clean[end:])
                end = end + tail.end() if tail else end
            else:
                while end < len(clean) and clean[end] != "{":
                    end += 1
                group = balanced(clean, end)
                end = group[1] if group else end
            result.setdefault(name, Definition(name, snippet(match.start(), end), file, definer, match.start()))
            continue
        if definer == "newcolumntype":
            group = balanced(clean, index)
            if group is None:
                continue
            name = "col:" + group[0].strip()
        elif definer in DEFINERS_ENVIRONMENT:
            group = balanced(clean, index)
            if group is None:
                continue
            name = "env:" + group[0].strip()
        else:
            if index < len(clean) and clean[index] == "{":
                group = balanced(clean, index)
                if group is None:
                    continue
                name = group[0].strip()
            else:
                command = re.match(r"\\[A-Za-z@]+", clean[index:])
                if not command:
                    continue
                name = command.group(0)
                group = (None, index + command.end())
            if not name.startswith("\\"):
                continue
        # The definition ends after its optional/mandatory groups.
        end = group[1]
        for _ in range(8):
            probe = _skip_space(clean, end)
            if probe < len(clean) and clean[probe] in "[{(":
                closing = {"[": "]", "{": "}", "(": ")"}[clean[probe]]
                part = balanced(clean, probe, clean[probe], closing)
                if part is None:
                    break
                end = part[1]
                # Stop after the body: newcommand has exactly one mandatory body group,
                # environments two, document commands two.
                if clean[probe] == "{":
                    groups = getattr(snippet, "_groups", 0) + 1
                    snippet._groups = groups  # type: ignore[attr-defined]
                    limit = 2 if definer in DEFINERS_ENVIRONMENT or "Document" in definer else 1
                    if definer in {"newif", "newlength", "newsavebox", "newtoks", "newcounter"}:
                        limit = 0
                    if groups >= limit:
                        break
            else:
                break
        snippet._groups = 0  # type: ignore[attr-defined]
        if definer == "newif":
            base = name[3:] if name.startswith("\\if") else name[1:]
            for derived in ("\\" + base + "true", "\\" + base + "false"):
                result.setdefault(derived, Definition(derived, snippet(match.start(), end), file, definer, match.start()))
        result.setdefault(name, Definition(name, snippet(match.start(), end), file, definer, match.start()))
    for match in re.finditer(r"\\newtheorem\*?\{([^}]*)\}", clean):
        name = "env:" + match.group(1).strip()
        result.setdefault(name, Definition(name, snippet(match.start(), clean.find("\n", match.end()) if "\n" in clean[match.end():] else len(clean)), file,
                                           "newtheorem", match.start()))
    return result


def packages(text: str) -> list[str]:
    clean = strip_comments(text)
    result = []
    for call in calls(clean, ["usepackage", "RequirePackage"]):
        for part in call.arguments[0].split(","):
            if part.strip() and part.strip() not in result:
                result.append(part.strip())
    return result


def uses(text: str) -> set[str]:
    """Command, environment and column-type names a file uses."""
    clean = strip_comments(text)
    result = {"\\" + name for name in re.findall(r"\\([A-Za-z@]+)", clean)}
    result.update("env:" + name.strip() for name in re.findall(r"\\begin\s*\{([^}]*)\}", clean))
    for call in calls(clean, ["begin"], arguments=1, max_optional=0):
        environment = call.arguments[0].strip()
        if environment not in TABULAR_ENVIRONMENTS:
            continue
        index = _skip_space(clean, call.end)
        if environment in {"tabular*", "tabularx", "xltabular", "tabulary"}:
            width = balanced(clean, index)
            if width is None:
                continue
            index = _skip_space(clean, width[1])
        if index < len(clean) and clean[index] == "[":
            option = balanced(clean, index, "[", "]")
            index = _skip_space(clean, option[1]) if option else index
        spec = balanced(clean, index)
        if spec is None:
            continue
        depth = 0
        for char in spec[0]:
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
            elif depth == 0 and char.isalpha():
                result.add("col:" + char)
    return result


def bib_entries(text: str) -> dict[str, str]:
    result = {}
    for match in re.finditer(r"@([A-Za-z]+)\s*\{\s*([^,\s{}]+)\s*,", text):
        if match.group(1).lower() in {"comment", "string", "preamble"}:
            continue
        brace = text.index("{", match.start())
        group = balanced(text, brace)
        end = group[1] if group else len(text)
        result.setdefault(match.group(2), text[match.start():end])
    return result


def cited_keys(text: str) -> list[str]:
    keys = []
    for group in CITE_COMMANDS.findall(strip_comments(text)):
        for key in group.split(","):
            key = key.strip()
            if key and key not in keys and key != "*":
                keys.append(key)
    return keys


def is_generated(path: str, raw: bytes | None) -> bool:
    if "generated" in PurePosixPath(path).parts:
        return True
    if raw is None:
        return False
    text = raw[:4096].decode("utf-8", errors="replace").lstrip("\ufeff")
    first = next((line.strip() for line in text.splitlines() if line.strip()), "")
    return first.startswith(GENERATED_MARKERS)


def standalone(text: str) -> bool:
    clean = strip_comments(text)
    return text.startswith("% thoughts:standalone-import\n") or bool(re.search(r"(?m)^\s*\\documentclass\b", clean))


def has_bibliography(text: str) -> bool:
    clean = strip_comments(text)
    return bool(re.search(r"\\(manualBibliography|bibliography|printbibliography)(?![A-Za-z@])", clean))


