"""Review cards made inside HTML attachment pages (docs/HTML_ATTACHMENTS.md, "Review cards").

Such a card is anchored by its remembered text (``text_quote``) and page state, not by
source markers: attachment text is often generated by the page's own scripts. Its primary
has ``created_in: "html_attachment"`` and no PDF geometry; ``source_link.state`` is the
terminal ``html_attachment``. Source linking, reanchoring and page fingerprints never
touch it (``is_attachment_card``). The shape is validated in ``schemas``; this module
adds the checks that need the database.
"""
from __future__ import annotations

import hashlib
import json

from sqlalchemy import select

from .operations import OperationConflict

CAPABILITY = "html_attachment_cards_v1"
CREATED_IN = "html_attachment"
SOURCE_LINK_STATE = "html_attachment"
UNKNOWN = "html_attachment_unknown"
_MAX_MANIFEST_BYTES = 2_000_000


class HtmlAttachmentUnknown(OperationConflict):
    """The card names an attachment version its owner document never had."""

    error_code = UNKNOWN


def is_attachment_card(payload: object) -> bool:
    if not isinstance(payload, dict):
        return False
    primary = payload.get("primary")
    link = payload.get("source_link")
    return ((isinstance(primary, dict) and primary.get("created_in") == CREATED_IN)
            or (isinstance(link, dict) and link.get("state") == SOURCE_LINK_STATE))


def _attachment(primary: dict) -> tuple[str, str]:
    ref = primary.get("html_attachment") or {}
    return ref.get("path"), ref.get("sha256")


def _pairs(resources: object) -> set[tuple[str, str]]:
    if not isinstance(resources, list):
        return set()
    return {(item.get("path"), item.get("sha256")) for item in resources
            if isinstance(item, dict) and item.get("kind", "html_attachment") == "html_attachment"}


def _verified_json(store, digest: object) -> object:
    if store is None or not isinstance(digest, str):
        return None
    try:
        path = store.path(digest)
        if path.stat().st_size > _MAX_MANIFEST_BYTES:
            return None
        raw = path.read_bytes()
    except (OSError, ValueError):
        return None
    if hashlib.sha256(raw).hexdigest() != digest:
        return None
    try:
        return json.loads(raw)
    except ValueError:
        return None


def _manifest_versions(session, store, project: str) -> set[tuple[str, str]]:
    """Every version of the folder's attachment manifest: the current file and its revision log."""
    from .html_attachments import MANIFEST
    from .models import Operation, SourceFile

    path = f"{project}/{MANIFEST}"
    digests = [payload.get("result_object_sha256") for payload in session.scalars(select(Operation.payload).where(
        Operation.entity_type == "source", Operation.entity_id == path,
        Operation.outcome.in_(("applied", "merged")))) if isinstance(payload, dict)]
    current = session.get(SourceFile, path)
    if current is not None:
        digests.append(current.object_sha256)
    pairs: set[tuple[str, str]] = set()
    for digest in dict.fromkeys(digests):
        manifest = _verified_json(store, digest)
        if isinstance(manifest, dict):
            pairs |= _pairs(manifest.get("attachments"))
    return pairs


def known_attachment(session, store, primary: dict) -> bool | None:
    """Whether the owner PDF links can reach this attachment version.

    None when the owner document is unknown to the server (nothing to check against).
    Known: an ``html_attachment`` resource of the owner's current publication or of the
    exact PDF the card names (its source closure), or any version of the attachment
    manifest of the path's folder.
    """
    from .models import Publication
    from .published_source_maps import LinkUnresolved, exact_manifest_record

    publication = session.get(Publication, f"{primary.get('pdf_stem')}.pdf")
    if publication is None:
        return None
    pair = _attachment(primary)
    if pair in _pairs((publication.metadata_json or {}).get("source_resources")):
        return True
    if store is not None:
        try:
            _identity, manifest = exact_manifest_record(session, store, publication.filename,
                                                        primary.get("pdf_sha256"))
        except (LinkUnresolved, OSError, ValueError):
            manifest = None
        if isinstance(manifest, dict) and pair in _pairs(manifest.get("resources")):
            return True
    return pair in _manifest_versions(session, store, pair[0].partition("/")[0])


def check_card(session, store, operation, previous_payload: dict | None) -> None:
    """Refuse a card naming an attachment version its owner never had (``html_attachment_unknown``).

    Checked when the card is made and whenever its owner or attachment changes, so a later
    edit (tags, sliders, a note) never fails because the attachment changed since.
    """
    primary = operation.payload.get("primary")
    if operation.entity_type != "review_card" or not isinstance(primary, dict) \
            or primary.get("created_in") != CREATED_IN:
        return
    previous = (previous_payload or {}).get("primary") or {}

    def identity(value: dict) -> tuple:
        return value.get("created_in"), value.get("pdf_stem"), value.get("pdf_sha256"), _attachment(value)

    if isinstance(previous, dict) and identity(previous) == identity(primary):
        return
    if known_attachment(session, store, primary) is False:
        path, digest = _attachment(primary)
        raise HtmlAttachmentUnknown(
            f"The HTML attachment {path} ({digest[:12]}) is not one {primary.get('pdf_stem')}.pdf links to; "
            "Sync and open the attachment from its PDF again")
