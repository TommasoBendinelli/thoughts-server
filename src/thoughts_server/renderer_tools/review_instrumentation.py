# Include staging/verification changes even when the shared TeX hooks are unchanged.
INSTRUMENTATION_SHA256 = hashlib.sha256(
    f"{INSTRUMENTATION_VERSION}:{INSTRUMENTATION_TEX}".encode("utf-8")
).hexdigest()


def _proposal_command(preview_proposal_id: str | None) -> str:
    if preview_proposal_id is None:
        return INSTRUMENTATION_TEX
    if not preview_proposal_id or any(
        character not in "abcdefghijklmnopqrstuvwxyz0123456789._:-" for character in preview_proposal_id
    ):
        raise ValueError("invalid proposal preview identity")
    start_marker = r"\NewExpandableDocumentCommand{\thoughtsAgentProposedEditCommand}{O{} +m +m +m +m}{%"
    end_marker = "\n}\n% Proposals may legitimately occur in a preamble"
    start = INSTRUMENTATION_TEX.find(start_marker)
    end = INSTRUMENTATION_TEX.find(end_marker, start)
    if start < 0 or end < 0:
        raise RuntimeError("proposal instrumentation template changed unexpectedly")
    replacement = rf"""\NewExpandableDocumentCommand{{\thoughtsAgentProposedEditCommand}}
  {{O{{}} +m +m +m +m}}{{%
  % Preview one proposal's original rendering while every other proposal keeps
  % the canonical proposed rendering.  This is installed only in an isolated
  % preview build and is never copied into authored source.
  % Keep this comparison fully expandable: grouping or assignments here would
  % insert TeX material between table rows and break commands such as noalign.
  \ifnum\pdfstrcmp{{\detokenize{{#2}}}}{{\detokenize{{{preview_proposal_id}}}}}=0
    #4%
  \else
    #5%
  \fi
}}"""
    return INSTRUMENTATION_TEX[:start] + replacement + INSTRUMENTATION_TEX[end + 2 :]


def stage_review_instrumentation(
    build_directory: Path,
    *,
    preview_proposal_id: str | None = None,
) -> Path:
    """Install the immutable v2 instrumentation in generated build state."""

    destination = build_directory / "thoughts-review-instrumentation-v2"
    destination.mkdir(parents=True, exist_ok=True)
    target = destination / "thoughts-review-correspondence-v2.tex"
    expected = _proposal_command(preview_proposal_id).encode("utf-8")
    if target.is_file() and target.read_bytes() == expected:
        return destination
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{target.name}.", dir=destination)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(expected)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)
    return destination


def wrapper_preamble(source: Path) -> str:
    """Return a wrapper that installs instrumentation before authored declarations execute."""

    escaped = str(source).replace("\\", "/").replace('"', r'\string"')
    return "\n".join(
        (
            r"\input{thoughts-review-correspondence-v2.tex}",
            r"\AtBeginDocument{\providecommand{\SourceLabel}[1]{\hypertarget{source-label:\detokenize{#1}}{}}}",
            r"\AtBeginDocument{\providecommand{\SourceLink}[3]{\href{manual-sourcelink:\detokenize{#1}?label=\detokenize{#2}}{#3}}}",
            r"\AtBeginDocument{\providecommand{\CrossSourceLink}[3]{\href{manual-cross-sourcelink:\detokenize{#1}?label=\detokenize{#2}}{#3}}}",
            # Every note gets \PdfLink, also one in a Project's default folder (no style file):
            # a Library PDF by its filename, wherever it is (doc_links.library_pdfs).
            r"\AtBeginDocument{\providecommand{\PdfLink}[3]{\href{manual-pdflink:\detokenize{#1}?anchor=\detokenize{#2}}{#3}}}",
            r"\AtBeginDocument{\providecommand{\CrossPdfLink}[3]{\href{manual-cross-pdflink:\detokenize{#1}?anchor=\detokenize{#2}}{#3}}}",
            # Retired commands: an old \TexLink/\CrossTexLink still typesets its text,
            # and link resolution leaves it inactive with a warning naming the replacement.
            r"\AtBeginDocument{\providecommand{\TexLink}[3]{\href{manual-texlink:\detokenize{#1}?label=\detokenize{#2}}{#3}}}",
            r"\AtBeginDocument{\providecommand{\CrossTexLink}[3]{\href{manual-cross-texlink:\detokenize{#1}?label=\detokenize{#2}}{#3}}}",
            rf'\input{{"{escaped}"}}',
            "",
        )
    )
